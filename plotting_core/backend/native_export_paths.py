"""Route only long native image exports through one owned short directory.

Origin's native exporter on this installation fails for sufficiently deep
staging paths. The conservative routing threshold is an operational guard,
not a universal Origin-version limit. Native files are copied byte-for-byte;
no raster/vector content is parsed, rewritten or overlaid.
"""

import hashlib
import json
import shutil
import tempfile
import uuid
from pathlib import Path


NATIVE_EXPORT_PATH_LIMIT = 240
NATIVE_PROJECT_PATH_LIMIT = 259


def path_units(path):
    """Windows path length in UTF-16 code units, excluding the null terminator."""
    return len(str(path).encode("utf-16-le")) // 2


def assert_project_path(path):
    if path is not None and path_units(Path(path).resolve()) > NATIVE_PROJECT_PATH_LIMIT:
        raise ValueError("Origin project save path exceeds the supported operational guard (%d UTF-16 units): %s; "
                         "choose a shorter final project directory; project save cannot use the image-export copy workaround" %
                         (NATIVE_PROJECT_PATH_LIMIT, path))


def _fingerprint(path):
    target = Path(path)
    digest = hashlib.sha256()
    with target.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return {"sha256": digest.hexdigest(), "bytes": target.stat().st_size}


class NativeExportPaths:
    """Context manager that preserves generated bytes, evidence and ownership."""

    def __init__(self, targets, graph_name, evidence_path, *, limit=NATIVE_EXPORT_PATH_LIMIT, temp_base=None):
        self.targets = {kind: Path(path).resolve() for kind, path in targets.items() if kind in ("png", "svg")}
        self.graph_name = str(graph_name)
        self.evidence_path = Path(evidence_path).resolve()
        self.limit = limit
        self.temp_base = Path(temp_base).resolve() if temp_base else Path(tempfile.gettempdir()).resolve()
        self.owned_root = None
        self.owner_token = uuid.uuid4().hex
        self.directory = next(iter(self.targets.values())).parent if self.targets else self.evidence_path.parent
        self.document = {"schema_version": 1, "status": "preparing", "routed": False,
                         "policy": "native Origin exports only; copy unchanged bytes from one owned short staging directory",
                         "export_path_guard_utf16_units": limit,
                         "guard_scope": "conservative operational routing threshold, not a claim about every Origin version",
                         "evidence": str(self.evidence_path), "mappings": [],
                         "cleanup": {"needed": False, "performed": False}}

    def _publish(self):
        self.evidence_path.parent.mkdir(parents=True, exist_ok=True)
        self.evidence_path.write_text(json.dumps(self.document, ensure_ascii=False, indent=2), encoding="utf-8")

    def __enter__(self):
        try:
            if any(path_units(path) > self.limit for path in self.targets.values()):
                root = Path(tempfile.mkdtemp(prefix="bop_", dir=str(self.temp_base))).resolve()
                self.owned_root = root
                self.directory = root
                (root / "_origin_export_owner.json").write_text(json.dumps({"token": self.owner_token}), encoding="utf-8")
                self.document.update(routed=True, native_directory=str(root))
                self.document["cleanup"]["needed"] = True
            else:
                self.document["native_directory"] = str(self.directory)
            for kind, task_path in self.targets.items():
                native_path = self.directory / task_path.name
                self.document["mappings"].append({"format": kind, "native_path": str(native_path),
                                                   "task_path": str(task_path), "task_path_units": path_units(task_path),
                                                   "native_path_units": path_units(native_path),
                                                   "status": "planned"})
                if path_units(native_path) > self.limit:
                    raise ValueError("even the owned temporary native export path exceeds the operational guard: %s; "
                                     "shorten the filename or configure a shorter system temporary directory" % native_path)
            self.document["status"] = "native_export_pending"
            self._publish()
            return self
        except Exception as exc:
            self.document.update(status="failed_before_export", error=str(exc))
            self._cleanup()
            self._publish()
            raise

    def _cleanup(self):
        if self.owned_root is None:
            return
        root = self.owned_root
        marker = root / "_origin_export_owner.json"
        try:
            # Verify the resolved absolute target is precisely the directory
            # created by this attempt and is directly under the declared Temp
            # base. Do not recursively remove arbitrary caller-provided paths.
            if (root.resolve() != root or root.parent.resolve() != self.temp_base or
                    not root.name.startswith("bop_") or root.is_symlink() or
                    json.loads(marker.read_text(encoding="utf-8")).get("token") != self.owner_token):
                raise RuntimeError("owned temporary export directory identity changed; cleanup refused")
            shutil.rmtree(str(root))
            self.document["cleanup"].update(performed=True, verified_owned_root=str(root))
        except Exception as exc:
            self.document["cleanup"].update(performed=False, diagnostic=str(exc), retained_directory=str(root))

    def __exit__(self, exc_type, exc, traceback):
        copy_errors, missing_exports = [], []
        for mapping in self.document["mappings"]:
            native, task = Path(mapping["native_path"]), Path(mapping["task_path"])
            if not native.is_file():
                mapping["status"] = "not_generated"
                missing_exports.append(mapping["format"])
                continue
            try:
                before = _fingerprint(native)
                mapping["native_fingerprint"] = before
                if native != task:
                    task.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(str(native), str(task))
                after = _fingerprint(task)
                mapping.update(task_fingerprint=after, bytes_equal=before == after,
                               status="preserved_unmodified" if before == after else "copy_mismatch")
                if before != after:
                    raise RuntimeError("native export byte identity differs after task copy")
            except Exception as copy_exc:
                mapping.update(status="preservation_failed", diagnostic=str(copy_exc))
                copy_errors.append(str(copy_exc))
        self.document["status"] = "failed" if exc is not None or copy_errors or missing_exports else "completed"
        if missing_exports:
            self.document["not_generated"] = missing_exports
        if exc is not None:
            self.document["native_error"] = str(exc)
        if copy_errors:
            self.document["preservation_errors"] = copy_errors
            # Generated evidence must not be destroyed when it cannot be copied
            # back. Keep this uniquely owned Temp directory and report its path.
            self.document["cleanup"].update(performed=False, retained_directory=str(self.owned_root),
                                            reason="preserve native files whose task copy failed")
        else:
            self._cleanup()
        self._publish()
        if copy_errors and exc is None:
            raise RuntimeError("native export preservation failed: %s; evidence: %s" %
                               (copy_errors, self.evidence_path))
        if missing_exports and exc is None:
            raise RuntimeError("native export file(s) were not generated: %s; evidence: %s" %
                               (missing_exports, self.evidence_path))
        return False
